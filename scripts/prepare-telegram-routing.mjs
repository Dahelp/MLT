import {mkdir, writeFile} from 'node:fs/promises';
import path from 'node:path';

const destination = process.argv[2];
if (!destination) throw new Error('Destination file is required');
const chatId = (process.env.MLT_TELEGRAM_SALES_CHAT_ID || '').trim();
if (chatId && !/^-?[1-9][0-9]*$/.test(chatId)) throw new Error('Sales chat ID must be a Telegram numeric chat ID');
const departments = Object.fromEntries(['investments','tours'].map(name=>{
  const value=(process.env[`MLT_TELEGRAM_${name.toUpperCase()}_CHAT_ID`] || '').trim();
  if(value && !/^-?[1-9][0-9]*$/.test(value)) throw new Error(`${name} chat ID must be a Telegram numeric chat ID`);
  return [name,value];
}));
await mkdir(path.dirname(destination), {recursive:true});
// This PHP file returns a server-side setting without rendering it in HTTP responses.
await writeFile(destination, `<?php\n// Generated by production deployment.\nreturn ${JSON.stringify(chatId)};\n`);
await writeFile(path.join(path.dirname(destination),'telegram-department-destinations.php'), `<?php\n// Generated by production deployment.\nreturn [${Object.entries(departments).map(([name,value])=>`${JSON.stringify(name)} => ${JSON.stringify(value)}`).join(', ')}];\n`);
