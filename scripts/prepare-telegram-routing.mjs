import {mkdir, writeFile} from 'node:fs/promises';
import path from 'node:path';

const destination = process.argv[2];
if (!destination) throw new Error('Destination file is required');
const chatId = (process.env.MLT_TELEGRAM_SALES_CHAT_ID || '').trim();
if (chatId && !/^-?[1-9][0-9]*$/.test(chatId)) throw new Error('Sales chat ID must be a Telegram numeric chat ID');
await mkdir(path.dirname(destination), {recursive:true});
// This PHP file returns a server-side setting without rendering it in HTTP responses.
await writeFile(destination, `<?php\n// Generated by production deployment.\nreturn ${JSON.stringify(chatId)};\n`);
